-- GreenProof — species identification and care advice
--
-- WHAT THIS ADDS, AND WHAT IT DELIBERATELY IS NOT
--
-- Everything in this migration is ADVISORY. It exists to help the planter keep
-- the tree alive, which is the one thing the verification engine has never done.
-- The Auditor-General's report on Green Ghana names the gap directly: "No
-- funding allocated for post-planting care at all."
--
-- It is NOT a verification signal. `confidence`, `verdict` and `signals` are not
-- touched by any of this, and must not be. Every number in the pitch deck comes
-- out of that scoring path, and a component we cannot publish an error rate for
-- has no business influencing a payment decision.
--
-- WHY SEPARATE COLUMNS AND NOT INSIDE `signals`
--
-- Two reasons, both learned the hard way.
--
-- 1. `signals` is REPLACED WHOLESALE on every scoring run. That is exactly how
--    we destroyed the provenance tag marking six injected attack rows as
--    synthetic, making them indistinguishable from real pilot data in our own
--    database. Anything that must survive a re-score cannot live in `signals`.
--    Scoring is replayable by design; advice is not part of what gets replayed.
--
-- 2. Keeping advice structurally outside `signals` is the PROOF that it is not
--    part of the verdict, rather than a promise that it isn't. A reviewer can
--    confirm the boundary by reading the schema instead of trusting the code.

alter table checkins
  -- Optional fourth photo: a leaf, close enough to fill the frame. Species
  -- identification and health assessment both want foliage, and our two scored
  -- photos are a whole tree and a trunk — neither is what these models want.
  --
  -- OPTIONAL IS LOAD-BEARING, NOT A CONVENIENCE. A visit must complete with this
  -- missing: the capture screens are what run live on stage, and "designed to
  -- degrade, not break" is one of the four claims this project is built on.
  -- It is also why the feature works at all on the 9 pilot check-ins, which were
  -- captured before this column existed.
  add column if not exists leaf_photo    text,

  -- Derived results. Service-role only, same rule as confidence/verdict/signals.
  add column if not exists species_guess jsonb,
  add column if not exists advice        jsonb;

-- ---------------------------------------------------------------------------
-- Grants — column-level, as everywhere else in this schema
-- ---------------------------------------------------------------------------
-- RLS controls WHICH ROWS you touch; it cannot stop you writing a particular
-- COLUMN. So the client is granted the photo it supplies and nothing else.
--
-- `species_guess` is deliberately NOT granted even though species is "only"
-- advisory today. A tree's species being checkable against its own history is
-- the natural next signal — "the species at visit 4 is not the species at
-- registration" catches tree-swapping independently of scene_match, which is
-- our weakest measured signal. A client that could write its own species guess
-- would defeat that check before we ever built it.
grant insert (leaf_photo) on checkins to authenticated;

comment on column checkins.leaf_photo is
  'Optional foliage close-up. Never scored, never gated on. Used only by the '
  'advisory layer for species identification and health assessment.';

comment on column checkins.species_guess is
  'Advisory species identification. Written only by the ML service. NOT a '
  'verification signal and never folded into confidence.';

comment on column checkins.advice is
  'Advisory health assessment and care recommendations for the planter, '
  'generated by an LLM. Written only by the ML service. NOT a verification '
  'signal and never folded into confidence.';

-- ---------------------------------------------------------------------------
-- Refresh the review queue view
-- ---------------------------------------------------------------------------
-- NOT COSMETIC, AND NOT OPTIONAL.
--
-- `review_queue` is defined as `select c.*, ...` and Postgres expands that star
-- AT CREATION TIME. The view therefore still returns the column list as it stood
-- in migration 0006, and would silently omit the three columns added above -
-- while the TypeScript type `ReviewQueueRow = Checkin & {...}` now promises they
-- are there. That mismatch does not fail loudly; it hands the reviewer
-- `undefined` and looks like missing data.
--
-- DROP rather than CREATE OR REPLACE: replace may only append columns to the
-- end of a view, and `c.*` inserts the new ones in the MIDDLE, ahead of
-- tag_code. Postgres rejects that with "cannot change name of view column".
drop view if exists review_queue;

create view review_queue as
  select c.*,
         t.tag_code,
         t.species,
         t.lat  as tree_lat,
         t.lng  as tree_lng,
         (c.audit_sample and c.verdict = 'verified') as is_audit
    from checkins c
    join trees t on t.id = c.tree_id
   where c.reviewed_at is null
     and (c.verdict = 'review' or (c.audit_sample and c.verdict = 'verified'))
   order by c.audit_sample desc, c.confidence asc nulls first;

-- Dropping the view dropped its grant with it. Restoring it is what makes the
-- reviewer screen work at all, and forgetting it is a "permission denied for
-- table review_queue" in front of an audience.
grant select on review_queue to authenticated;

-- AND EXPLICITLY CLOSE IT TO anon AGAIN.
--
-- 0008 revoked anon's access across the schema and warned in its own comment
-- that "if a table is added later it inherits the default grant again and would
-- silently reopen this hole". Dropping and recreating this view makes it a
-- later-added object, which is precisely that case.
--
-- 0008's `alter default privileges` should already cover it, but only for
-- objects created by the same role that ran the ALTER - which is an assumption
-- about who runs a migration, not a guarantee. This view joins every check-in to
-- its tree, so an anon SELECT would expose the whole pilot dataset including
-- GPS positions. One redundant line is the correct price for removing that
-- dependency on who happened to paste the SQL.
revoke all on review_queue from anon;
